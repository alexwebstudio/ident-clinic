const order = ["implantation", "orthodontics", "therapy", "kids", "prosthetics", "surgery", "hygiene", "esthetics"];

// Врачи — только реальные, по отзывам пациентов. Где врач не подтверждён, блок «Ведёт услугу» скрыт.
const doctorBySlug: Record<string, string> = {
  orthodontics: "aynura-altynbaevna",
  kids: "karina-nurlibekovna",
};

export const services: Service[] = order.map((slug, index) => {
  const item = catalog.find((service) => service.slug === slug)!;
  return { ...item, number: String(index + 1).padStart(2, "0"), doctorSlug: doctorBySlug[slug] ?? "" };
});

export function getService(slug: string) {
  return services.find((item) => item.slug === slug);
}

